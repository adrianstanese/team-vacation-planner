// Puts every i18n/<code>.json translation into the app's dictionaries and writes lib/langMeta.ts.
// Safe to run again: blocks it wrote earlier are replaced, hand-written languages are never touched.
//   node scripts/i18n/check.mjs && node scripts/i18n/apply.mjs
import fs from "node:fs";
import { DICTS, closing } from "./lib.mjs";

const HAND = ["en", "fr", "de", "es", "pt", "ro", "hu", "sv", "it", "bg", "ar"]; // written in the source files
const codes = fs.readdirSync("i18n").filter(f => /^[a-z]{2}\.json$/.test(f)).map(f => f.slice(0, 2)).sort();
const langs = Object.fromEntries(codes.map(c => [c, JSON.parse(fs.readFileSync(`i18n/${c}.json`, "utf8"))]));
for (const c of codes) if (HAND.includes(c)) throw new Error(`${c} is a hand-written language; edit it in the source files`);
const base = JSON.parse(fs.readFileSync("i18n/base.json", "utf8"));

const START = c => `/*i18n:${c}*/`, END = c => `/*/i18n:${c}*/`;
const strip = src => src.replace(/\n?[ \t]*\/\*i18n:([a-z]{2})\*\/[\s\S]*?\/\*\/i18n:\1\*\//g, "");
// Only keys the base knows, in base order: nothing unexpected reaches the app
const clean = (c, id) => Object.fromEntries(Object.keys(base.groups[id].strings).filter(k => langs[c][id] && k in langs[c][id]).map(k => [k, langs[c][id][k]]));

const byFile = {};
for (const d of DICTS) (byFile[d.file] ||= []).push(d);
for (const [file, dicts] of Object.entries(byFile)) {
  let src = strip(fs.readFileSync(file, "utf8"));
  for (const d of dicts) {
    const at = src.indexOf(d.marker);
    if (at < 0) throw new Error(`marker not found: ${d.id}`);
    const open = src.indexOf("{", at + d.marker.length - 1), close = closing(src, open);
    if (d.single) { // v3Text: one const per language, then the list
      const stmtEnd = src.indexOf(";", close) + 1;
      const blocks = codes.map(c => `\n${START(c)}const ${c}: T = ${JSON.stringify(clean(c, d.id))};${END(c)}`).join("");
      src = src.slice(0, stmtEnd) + blocks + src.slice(stmtEnd);
      const list = /(const V_TX: Record<string, T> = \{)([^}]*)(\};)/.exec(src);
      if (!list) throw new Error("V_TX list not found");
      const names = [...new Set([...list[2].split(",").map(s => s.trim()).filter(s => s && HAND.includes(s)), ...codes])];
      src = src.replace(list[0], `${list[1]} ${names.join(", ")} ${list[3]}`);
      continue;
    }
    const before = src.slice(0, close).replace(/\s+$/, "");
    const comma = before.endsWith(",") || before.endsWith("{") ? "" : ",";
    const blocks = codes.map(c => `\n${START(c)}${c}:${JSON.stringify(clean(c, d.id))},${END(c)}`).join("");
    src = before + comma + blocks + "\n" + src.slice(close);
  }
  fs.writeFileSync(file, src);
}

const meta = Object.fromEntries(codes.map(c => {
  const L = langs[c]._lang;
  return [c, { name: L.name, label: L.label, flag: L.flag, home: L.home, locale: L.locale, dir: L.dir, fonts: L.fonts || "" }];
}));
fs.writeFileSync("lib/langMeta.ts", `// GENERATED by scripts/i18n/apply.mjs from the _lang block of each i18n/<code>.json. Do not edit by hand.
// Languages added through translation files (the first 11 are written in the source files).
export type LangMeta = { name: string; label: string; flag: string; home: string; locale: string; dir: "ltr" | "rtl"; fonts: string };
export const LANG_META: Record<string, LangMeta> = ${JSON.stringify(meta, null, 1)};
`);
console.log(`applied ${codes.length} language(s): ${codes.join(", ") || "none"} → ${Object.keys(byFile).length} files + lib/langMeta.ts`);
