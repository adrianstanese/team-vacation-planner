#!/usr/bin/env node
// Builds lib/holidayDates.ts: every public holiday (type "P", a day off by law) per country and region, 2026–2035,
// from the NonWorkingDays dataset (python-holidays). The planner uses these dates instead of hand-written rules.
//   node scripts/build-holiday-dates.mjs [path to NonWorkingDays lib/data/holidays]
// Countries without a dataset file (Kosovo, Ukraine) keep the rules in app/app.tsx.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SRC = process.argv[2] || path.resolve("../NonWorkingDays.nosync/lib/data/holidays");
const APP = fs.readFileSync(new URL("../app/app.tsx", import.meta.url), "utf8");
const codes = [...APP.slice(APP.indexOf("const EU_C")).split("\n")[0].matchAll(/\{c:"([A-Z]{2})"/g)].map(m => m[1]);
if (codes.length < 55) throw new Error("country list not found in app/app.tsx");
// Where the legal national list is minimal but most people also get regional days, a member without a region
// gets the days of the largest region.
const DEFAULT_REGION = { GB: "ENG", CH: "ZH", AU: "NSW", CA: "ON", BA: "BIH" };
// Sub-city entries in the dataset are not offered as regions
const SKIP_REGION = new Set(["Barcelona", "Augsburg", "Stadt Zurich", "NSW Western", "Andria", "Barletta", "Cesena", "Forli"]);
const OFFER_REGIONS = new Set(["ES", "DE", "CH", "AU", "CA", "GB", "BA", "US", "IN"]);
// Region names the dataset has wrong
const REGION_NAME_FIX = { IN: { TS: "Telangana" } };

const out = { HD: {}, HDR: {}, RN: {}, DEF: DEFAULT_REGION };
const pack = ds => {
  const by = {};
  for (const d of [...new Set(ds)].sort()) (by[d.slice(0, 4)] ||= []).push(d.slice(5, 7) + d.slice(8, 10));
  return Object.entries(by).map(([y, l]) => y + ":" + l.join(",")).join("|");
};
// Ukraine: under martial law (Law No. 2136-IX, Art. 6) public holidays are not days off (Labour Code Art. 73 does
// not apply). Set to false when martial law ends, then rebuild.
const UA_MARTIAL_LAW = true;
const EXTRA = fileURLToPath(new URL("./data/", import.meta.url)); // countries python-holidays lacks (Kosovo)
const missing = [];
for (const cc of codes) {
  if (cc === "UA" && UA_MARTIAL_LAW) { out.HD.UA = Array.from({ length: 10 }, (_, i) => (2026 + i) + ":").join("|"); continue; }
  let f = path.join(SRC, cc.toLowerCase() + ".json");
  if (!fs.existsSync(f)) f = path.join(EXTRA, cc.toLowerCase() + ".json");
  if (!fs.existsSync(f)) { missing.push(cc); continue; }
  const j = JSON.parse(fs.readFileSync(f, "utf8"));
  const pub = j.h.filter(r => String(r[3] || "").includes("P") && r[0] >= "2026" && r[0] < "2036"); // years the planner shows
  out.HD[cc] = pack(pub.filter(r => !r[4]).map(r => r[0]));
  if (OFFER_REGIONS.has(cc)) {
    const regs = {};
    for (const r of pub) if (r[4]) for (const g of r[4]) if (!SKIP_REGION.has(g)) (regs[g] ||= []).push(r[0]);
    out.HDR[cc] = Object.fromEntries(Object.entries(regs).map(([g, ds]) => [g, pack(ds)]));
    out.RN[cc] = Object.fromEntries(Object.entries(j.regions || {}).filter(([g]) => !SKIP_REGION.has(g)).map(([g, n]) => [g, REGION_NAME_FIX[cc]?.[g] || n]));
  }
}
const ts = `// GENERATED by scripts/build-holiday-dates.mjs from the NonWorkingDays dataset (python-holidays ${JSON.parse(fs.readFileSync(path.join(SRC, "ro.json"), "utf8")).source.version}).
// Do not edit by hand. Format per country: "YYYY:MMDD,MMDD|YYYY:...". HD = national public holidays,
// HDR = extra public holidays of a region, RN = region names, DEF = region used when a member has none.
export const HD: Record<string, string> = ${JSON.stringify(out.HD)};
export const HDR: Record<string, Record<string, string>> = ${JSON.stringify(out.HDR)};
export const RN: Record<string, Record<string, string>> = ${JSON.stringify(out.RN)};
export const DEF: Record<string, string> = ${JSON.stringify(out.DEF)};
const cache = new Map<string, string[] | null>();
function unpack(s: string | undefined, year: number): string[] | null {
  if (!s) return null;
  const y = String(year), part = s.split("|").find(p => p.startsWith(y + ":"));
  if (!part) return s.split("|").some(p => p.slice(0, 4) === y) ? [] : null;
  return part.slice(5).split(",").filter(Boolean).map(md => y + "-" + md.slice(0, 2) + "-" + md.slice(2));
}
// Years the dataset covers (same for every country)
export const DATA_YEARS = { from: 2026, to: 2035 };
const covered = (year: number) => year >= DATA_YEARS.from && year <= DATA_YEARS.to;
/** National public holidays (plus the default region's, see DEF); null when the data does not cover it. */
export function nationalDates(cc: string, year: number): string[] | null {
  if (!HD[cc] || !covered(year)) return null;
  const k = cc + year;
  if (!cache.has(k)) {
    const base = unpack(HD[cc], year) || [];
    const def = DEF[cc] ? unpack(HDR[cc]?.[DEF[cc]], year) || [] : [];
    cache.set(k, [...new Set([...base, ...def])].sort());
  }
  return cache.get(k)!;
}
/** National plus one region's public holidays; null when the data does not cover it. */
export function regionalDates(cc: string, region: string, year: number): string[] | null {
  if (!HD[cc] || !covered(year) || !HDR[cc] || !(region in HDR[cc] || region in (RN[cc] || {}))) return null;
  const base = unpack(HD[cc], year) || [];
  const reg = unpack(HDR[cc][region], year) || [];
  return [...new Set([...base, ...reg])].sort();
}
`;
fs.writeFileSync(new URL("../lib/holidayDates.ts", import.meta.url), ts);
console.log("countries:", Object.keys(out.HD).length, "| regions for:", Object.keys(out.HDR).join(","), "| no data (rules kept):", missing.join(",") || "none", "| bytes:", ts.length);
