/** A template text in the given language with its placeholders filled in; falls back to English. */
export function tpl(lang: string, key: string, vars?: Record<string, string | number>): string {
  let s = (TEMPLATE_TX[lang] && TEMPLATE_TX[lang][key]) || TEMPLATE_TX.en[key] || "";
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
